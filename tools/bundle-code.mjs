/**
 * bundle-code.mjs — write docs/campus-map-code.md: every map source file in one
 * reviewable, copy-pasteable document (app code + data + regeneration tooling).
 *
 *   node tools/bundle-code.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const out = [];
const w = (s = '') => out.push(s);

const FILES = [
  ['src/lib/geo.js', 'Geodesy helpers — distances, polygon area/centroid, bounds, point-in-polygon'],
  ['src/lib/campusData.js', 'Campus data access layer — categories, layer zoom table, search, nearest place'],
  ['src/types/index.js', 'Domain types — campus geofence derived from the surveyed wall'],
  ['src/components/map/mapIcons.js', 'Leaflet icon factories + marker dispersion'],
  ['src/components/map/CampusLayers.jsx', 'Data-driven campus layers (wall, roads, greens, water, parking, trees, gates, footprints)'],
  ['src/components/InteractiveMap.jsx', 'The map surface — Satellite / Campus layout / Website engines'],
  ['src/components/MapLocationPickerModal.jsx', 'Location picker rebuilt on the shared surveyed layers'],
  ['src/data/campusLayout.json', 'Campus layout data (generated by tools/build-campus-data.mjs)'],
  ['src/data/bbitPlaces.json', 'The 50 curated places with real footprints (generated)'],
];

w('# BBIT campus map — complete code bundle');
w();
w('Everything the map needs, in dependency order. Drop the `src/lib`, `src/components/map` and');
w('`src/data` files into the project and the map runs; `src/types/index.js` is the only file that');
w('replaces an existing one.');
w();
w('| # | File | Role |');
w('| - | ---- | ---- |');
FILES.forEach(([f, role], i) => w(`| ${i + 1} | \`${f}\` | ${role} |`));
w();
w('Generated data can be rebuilt with `node tools/build-campus-data.mjs` from');
w('`tools/imagery/campus-spec.json` (pixel-space authoring spec).');
w();
w('---');
w();

FILES.forEach(([file, role], i) => {
  const abs = path.join(ROOT, file);
  const body = fs.readFileSync(abs, 'utf8');
  const lang = file.endsWith('.json') ? 'json' : 'jsx';
  w(`## ${i + 1}. \`${file}\``);
  w();
  w(`_${role}_`);
  w();
  w(`\`\`\`${lang}`);
  w(body.replace(/\n+$/, ''));
  w('```');
  w();
});

// ---- optional appendix: regeneration tooling -------------------------------
w('---');
w();
w('## Appendix — regeneration tooling (optional)');
w();
w('The two files below rebuild every polygon in the bundle from the pixel-space');
w('authoring spec. `tools/imagery/transforms.json` holds the georeference');
w('(centre pixel + metres-per-pixel) they depend on.');
w();
for (const [file, role] of [
  ['tools/build-campus-data.mjs', 'Spec (screenshot pixel space) → WGS84 data, with layout QA'],
  ['tools/imagery/campus-spec.json', 'The campus, authored in pixel space — edit this to move blocks'],
]) {
  const body = fs.readFileSync(path.join(ROOT, file), 'utf8');
  w(`### \`${file}\``);
  w();
  w(`_${role}_`);
  w();
  w(`\`\`\`${file.endsWith('.json') ? 'json' : 'js'}`);
  w(body.replace(/\n+$/, ''));
  w('```');
  w();
}

fs.mkdirSync(path.join(ROOT, 'docs'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'docs/campus-map-code.md'), out.join('\n') + '\n');
console.log('bundle written:', out.length, 'lines');
